/**
 * Generate the symbol-prefix header for the vendored zstd decoder.
 *
 * The decoder is compiled into this pod, and RN apps usually link pods statically. If the host app
 * also links a libzstd (another pod, a transitive dependency), both copies define the same global
 * `ZSTD_*` symbols. On Apple's static-link model that does not reliably produce a duplicate-symbol
 * error — the linker can satisfy our undefined references from the *other* archive instead, so the
 * decoder we pinned and tested is not necessarily the one that runs. Two zstd builds are ABI
 * compatible enough to link and different enough to misbehave.
 *
 * Visibility does not fix this: `-fvisibility=hidden` controls who may see a symbol, not what it
 * is called, and the name stays global in the object file. The names themselves have to be unique.
 *
 * So every global symbol the amalgamation defines is renamed through a generated `#define` header,
 * force-included when the C is compiled. The list is derived from the compiled object rather than
 * hand-written, so updating zstd cannot silently leave a new symbol unprefixed.
 *
 * Run after changing `ios/vendor/zstddeclib.c`: `npm run gen:zstd-prefix`.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const VENDOR = 'packages/rn/ios/vendor';
const PREFIX = 'DashOtaZ_';
const HEADER = join(VENDOR, 'zstd_symbol_prefix.h');

const work = mkdtempSync(join(tmpdir(), 'zstd-prefix-'));
try {
  const object = join(work, 'zstddeclib.o');
  execFileSync('cc', ['-c', '-O1', '-w', join(VENDOR, 'zstddeclib.c'), '-I', VENDOR, '-o', object]);

  // Defined, externally visible symbols only: T (text), D/B (data/bss), S (other section).
  const symbols = execFileSync('nm', ['-g', '-U', object], { encoding: 'utf8' })
    .split('\n')
    .map((line) => line.trim().match(/^[0-9a-f]+\s+[TDBSCI]\s+_(\S+)$/i))
    .filter((m) => m !== null)
    .map((m) => m[1])
    .filter((name) => !name.startsWith(PREFIX))
    .sort();

  if (symbols.length === 0) throw new Error('no global symbols found — did the compile succeed?');

  // Names the amalgamation #undefs partway through would lose the rename with them: upstream does
  // `#define ZSTD_isError ERR_isError` for inlining, then `#undef ZSTD_isError` before defining the
  // real function, which drops our macro too and emits the symbol unprefixed. An asm label is not a
  // macro, so it survives. Prototypes cannot be generated reliably, so these are declared by hand —
  // and `npm run lint:native` fails the build if this list ever stops covering them.
  const source = readFileSync(join(VENDOR, 'zstddeclib.c'), 'utf8');
  const undefd = new Set([...source.matchAll(/^\s*#\s*undef\s+(\S+)/gm)].map((m) => m[1]));
  const ASM_LABELLED = {
    ZSTD_isError: 'unsigned ZSTD_isError(size_t result)',
  };

  const unhandled = symbols.filter((name) => undefd.has(name) && !(name in ASM_LABELLED));
  if (unhandled.length > 0) {
    throw new Error(
      `the amalgamation #undefs ${unhandled.join(', ')}, which drops the rename. Add a prototype to ` +
        'ASM_LABELLED in this script.',
    );
  }

  const macros = symbols.filter((name) => !undefd.has(name)).map((name) => `#define ${name} ${PREFIX}${name}`);
  const labels = symbols
    .filter((name) => undefd.has(name))
    .map((name) => `${ASM_LABELLED[name]} __asm__("_${PREFIX}${name}");`);
  const body = [macros.join('\n'), '', '/* #undef-proof: see the script. */', ...labels].join('\n');
  writeFileSync(
    HEADER,
    `// GENERATED by scripts/generate-zstd-prefix.mjs — do not edit.
//
// Renames every global symbol the vendored zstd decoder defines, so this copy cannot collide with
// (or be silently replaced by) a libzstd the host app links. See the script for why visibility
// flags are not enough. Regenerate with \`npm run gen:zstd-prefix\` after updating the vendored
// amalgamation.
//
// ${symbols.length} symbols, prefix ${PREFIX}
#ifndef DASHOTA_ZSTD_SYMBOL_PREFIX_H
#define DASHOTA_ZSTD_SYMBOL_PREFIX_H

#include <stddef.h>

${body}

#endif /* DASHOTA_ZSTD_SYMBOL_PREFIX_H */
`,
  );
  console.log(`wrote ${HEADER} — ${symbols.length} symbols prefixed with ${PREFIX}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
